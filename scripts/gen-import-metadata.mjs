function yamlList(items, indent = 8) {
  return items.map((item) => `${" ".repeat(indent)}- ${item}`).join("\n");
}

function owned({
  name,
  schema = "public",
  insert = [],
  select = [],
  update = [],
  allowDelete = false,
  extraInsertSet = "",
}) {
  const parts = [
    `table:`,
    `  name: ${name}`,
    `  schema: ${schema}`,
    `insert_permissions:`,
    `  - role: user`,
    `    permission:`,
    `      check:`,
    `        user_id:`,
    `          _eq: X-Hasura-User-Id`,
    `      set:`,
    `        user_id: x-hasura-user-id${extraInsertSet}`,
    `      columns:`,
    yamlList(insert),
    `select_permissions:`,
    `  - role: user`,
    `    permission:`,
    `      columns:`,
    yamlList(["user_id", ...select.filter((c) => c !== "user_id")]),
    `      filter:`,
    `        user_id:`,
    `          _eq: X-Hasura-User-Id`,
    `      allow_aggregations: false`,
  ];

  if (update.length) {
    parts.push(
      `update_permissions:`,
      `  - role: user`,
      `    permission:`,
      `      columns:`,
      yamlList(update),
      `      filter:`,
      `        user_id:`,
      `          _eq: X-Hasura-User-Id`,
      `      check:`,
      `        user_id:`,
      `          _eq: X-Hasura-User-Id`,
    );
  }

  if (allowDelete) {
    parts.push(
      `delete_permissions:`,
      `  - role: user`,
      `    permission:`,
      `      filter:`,
      `        user_id:`,
      `          _eq: X-Hasura-User-Id`,
    );
  }

  return `${parts.join("\n")}\n`;
}

